from io import BytesIO

from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas


def build_receipt(donation):
    buffer = BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=A4)
    width, height = A4
    left = 60
    y = height - 70

    pdf.setFont("Helvetica-Bold", 20)
    pdf.drawString(left, y, "Edu-Bridge")
    pdf.setFont("Helvetica", 10)
    pdf.drawString(left, y - 18, "Donation receipt")

    y -= 55
    pdf.setFont("Helvetica-Bold", 12)
    pdf.drawString(left, y, f"Receipt {donation.receipt_no}")
    pdf.setFont("Helvetica", 10)
    pdf.drawString(left, y - 18, f"Date: {donation.created_at.strftime('%d %b %Y, %H:%M')}")
    pdf.drawString(left, y - 34, f"Payment reference: {donation.payment_ref}")

    y -= 70
    rows = [
        ("Donor", donation.donor.name if donation.donor else "-"),
        ("Donor email", donation.donor.email if donation.donor else "-"),
        (
            "Program",
            donation.program.title if donation.program else "Direct student support",
        ),
        (
            "Student",
            donation.student.name if donation.student else "Not applicable",
        ),
        ("Donation type", donation.donation_type),
        ("Status", donation.status),
        ("Amount", f"INR {float(donation.amount):,.2f}"),
    ]
    for label, value in rows:
        pdf.setFont("Helvetica-Bold", 10)
        pdf.drawString(left, y, f"{label}:")
        pdf.setFont("Helvetica", 10)
        pdf.drawString(left + 130, y, str(value))
        y -= 20

    y -= 20
    pdf.setFont("Helvetica-Oblique", 9)
    pdf.drawString(left, y, "This receipt is issued for a mock payment. No real money moved.")
    pdf.setFont("Helvetica", 8)
    pdf.drawString(left, 45, "Edu-Bridge  |  Receipt generated by the platform")
    pdf.showPage()
    pdf.save()
    buffer.seek(0)
    return buffer
